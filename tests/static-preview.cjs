const fs = require("fs");
const path = require("path");
// Serves the production files directly through Playwright's fixture routing.
// This is useful in environments that prohibit even loopback network sockets.
// It exercises the UI and storage, but does not test a real service worker.
const staticMode = process.env.QA_STATIC === "1";
const contextOptions = staticMode ? { serviceWorkers: "block" } : {};
async function staticPreview(context, base) {
  if (!staticMode) return;
  const dist = path.resolve(__dirname, "../dist");
  const types = { ".html": "text/html", ".js": "application/javascript", ".css": "text/css", ".woff2": "font/woff2", ".webp": "image/webp", ".png": "image/png", ".svg": "image/svg+xml", ".webmanifest": "application/manifest+json" };
  await context.route(base + "/**", async (route) => {
    const pathname = decodeURIComponent(new URL(route.request().url()).pathname);
    let file = path.resolve(dist, "." + pathname);
    if (!file.startsWith(dist + path.sep) && file !== dist) return route.fulfill({ status: 400, body: "Invalid path" });
    if (!path.extname(file)) file = path.join(dist, "index.html");
    if (!fs.existsSync(file) || !fs.statSync(file).isFile()) return route.fulfill({ status: 404, body: "Not found" });
    return route.fulfill({ status: 200, contentType: types[path.extname(file)] || "application/octet-stream", body: fs.readFileSync(file) });
  });
}
async function exportBackup(page) {
  if (staticMode) {
    // Restricted child processes may not write browser downloads to disk.
    // Capture the actual blob generated by the Export action instead.
    await page.evaluate(() => {
      const original = URL.createObjectURL.bind(URL);
      URL.createObjectURL = (blob) => {
        window.__exportedBackup = blob;
        return original(blob);
      };
    });
    await page.getByRole("button", { name: "Export", exact: true }).click();
    return JSON.parse(await page.evaluate(() => window.__exportedBackup.text()));
  }
  const event = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export", exact: true }).click();
  const file = await (await event).path();
  return JSON.parse(fs.readFileSync(file, "utf8"));
}
module.exports = { staticPreview, staticMode, contextOptions, exportBackup };
